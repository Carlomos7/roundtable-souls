"""Generate the theme from tokens.json (technical specification §8.10, visual system): one source, two outputs.

    uv run python scripts/theme/gen_theme.py [--check | --dump]

Writes
    src/roundtable_souls/ui/qml/Theme/Theme.qml   the QML singleton (module Theme), with its qmldir
    src/roundtable_souls/ui/theme_tokens.py       the same roles as plain Python data, which ui/theme.py reads

Hand edits to either output are a bug: edit tokens.json and rerun. `--check` writes nothing and exits 1 when an
output is not current (a CI gate). `--dump` prints every colour role per theme with its OKLCH.

tokens.json follows the W3C design-tokens shape ({"$type", "$value"} leaves inside groups). Colour values may be
    "#RRGGBB" / "#RRGGBBAA"                             an sRGB hex
    {"colorSpace": "oklch", "components": [L, C, H]}   an OKLCH colour (L 0..1, C, H in degrees), gamut-mapped
    "{path.to.other.token}"                            a reference
and any colour token may carry "$extensions": {"roundtable": {"alpha": 0.7, "dL": 0.06, "composite": "{ref}"}}:
    alpha      the alpha the role is used at (15% status backgrounds, 70% secondary text ...)
    dL         an OKLCH lightness offset applied to the referenced colour (hover +0.06, press -0.10)
    composite  flatten the (translucent) value over this opaque colour and emit an opaque colour
The colour maths is in colour.py, shared with the contrast test (tests/unit/test_theme_contrast.py).
"""

