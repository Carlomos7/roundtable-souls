# ---------------------------------------------------------------------------------------------------- token tree
class Token:
    def __init__(self, path: str, type_: str, value: Any, ext: dict, description: str = ""):
        self.path = path
        self.type = type_
        self.raw = value
        self.ext = ext
        self.description = description
        self.value: Any = None  # resolved

    @property
    def name(self) -> str:
        """The generated property name: an explicit override, else camelCase of the path minus the theme prefix and
        any 'base' segment (theme.dark.surface.card -> surfaceCard, theme.dark.accent.base -> accent)."""
        if "name" in self.ext:
            return self.ext["name"]
        parts = self.path.split(".")
        if parts[0] == "theme":
            parts = parts[2:]
        parts = [p for p in parts if p != "base"]
        return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def load_tokens(path: Path = TOKENS) -> dict[str, Token]:
    data = json.loads(path.read_text(encoding="utf-8"))
    out: dict[str, Token] = {}

    def walk(node: dict, prefix: list[str], inherited_type: str | None):
        t = node.get("$type", inherited_type)
        if "$value" in node:
            ext = (node.get("$extensions") or {}).get("roundtable", {})
            out[".".join(prefix)] = Token(".".join(prefix), t or "", node["$value"], ext, node.get("$description", ""))
            return
        for k, v in node.items():
            if k.startswith("$"):
                continue
            if isinstance(v, dict):
                walk(v, prefix + [k], t)

    walk(data, [], None)
    return out


_REF = re.compile(r"^\{([^}]+)\}$")


def _ref(value: str) -> str | None:
    m = _REF.match(value)
    return m.group(1) if m else None


def _resolve_color(tok: Token, tokens: dict[str, Token], seen: tuple = ()) -> Rgba:
    if tok.value is not None:
        return tok.value
    if tok.path in seen:
        raise ValueError(f"reference cycle at {tok.path}")
    v = tok.raw
    if isinstance(v, str):
        ref = _ref(v)
        base = _resolve_color(tokens[ref], tokens, seen + (tok.path,)) if ref else parse_hex(v)
    elif isinstance(v, dict):
        space = v.get("colorSpace", "srgb")
        comps = v.get("components")
        alpha = float(v.get("alpha", 1.0))
        if space == "oklch" and comps:
            r, g, b = oklch_to_srgb(*comps)
            base = (r, g, b, alpha)
        elif space == "srgb":
            if "hex" in v:
                r, g, b, _ = parse_hex(v["hex"])
            elif comps:
                r, g, b = comps[0], comps[1], comps[2]
            else:
                raise ValueError(f"{tok.path}: an srgb colour needs hex or components")
            base = (r, g, b, alpha)
        else:
            raise ValueError(f"{tok.path}: unsupported colorSpace {space}")
    else:
        raise ValueError(f"{tok.path}: bad colour value {v!r}")
    if "dL" in tok.ext:
        base = shift_lightness(base, float(tok.ext["dL"]))
    if "alpha" in tok.ext:
        base = (base[0], base[1], base[2], float(tok.ext["alpha"]))
    if "composite" in tok.ext:
        ref = _ref(tok.ext["composite"])
        bg = _resolve_color(tokens[ref], tokens, seen + (tok.path,)) if ref else parse_hex(tok.ext["composite"])
        base = composite(base, bg)
    tok.value = base
    return base


def _resolve_scalar(tok: Token, tokens: dict[str, Token]) -> Any:
    v = tok.raw
    ref = _ref(v) if isinstance(v, str) else None
    if ref:
        return _resolve_scalar(tokens[ref], tokens)
    if tok.type == "dimension":
        if isinstance(v, dict):
            return float(v["value"])
        return float(str(v).replace("px", ""))
    if tok.type == "duration":
        if isinstance(v, dict):
            return float(v["value"])
        return float(str(v).replace("ms", ""))
    return v


def resolve_all(tokens: dict[str, Token]) -> None:
    for tok in tokens.values():
        if tok.type == "color":
            _resolve_color(tok, tokens)
        else:
            tok.value = _resolve_scalar(tok, tokens)


VARIANTS: dict[str, str] = {"tarnished": "dark"}  # variant -> the theme it overrides (Tarnished = dark + olive)


def theme_roles(theme: str, tokens: dict[str, Token]) -> dict[str, Token]:
    """{propertyName: Token} for one theme; a variant is its base theme's roles with the variant's overrides on top."""
    base = {t.name: t for p, t in tokens.items() if p.startswith(f"theme.{VARIANTS.get(theme, theme)}.")}
    if theme in VARIANTS:
        over = {t.name: t for p, t in tokens.items() if p.startswith(f"theme.{theme}.")}
        unknown = set(over) - set(base)
        if unknown:
            raise SystemExit(
                f"tokens.json: theme.{theme} overrides roles {sorted(unknown)} that theme.{VARIANTS[theme]} lacks"
            )
        base = {**base, **over}
    return base


def theme_colors(theme: str, tokens: dict[str, Token] | None = None) -> dict[str, Rgba]:
    """{propertyName: rgba} for one theme ("dark" / "light" / a variant); what the contrast test consumes."""
    tokens = tokens or load_tokens()
    resolve_all(tokens)
    return {n: t.value for n, t in theme_roles(theme, tokens).items() if t.type == "color"}


def shared_tokens(tokens: dict[str, Token]) -> dict[str, Token]:
    return {p: t for p, t in tokens.items() if not p.startswith(("theme.", "primitive.", "ramp."))}


